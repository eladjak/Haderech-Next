// ----------------------------------------------------------------------
// Helper: pick prompt by mode
// ----------------------------------------------------------------------
export type CoachMode = "coach" | "debrief" | "mentor" | "practice" | "analysis";

export function getSystemPromptForMode(mode: CoachMode): string {
  switch (mode) {
    case "coach":
      return COACH_SYSTEM_PROMPT;
    case "debrief":
      return DEBRIEF_SYSTEM_PROMPT;
    case "mentor":
      return MENTOR_SYSTEM_PROMPT;
    default:
      // legacy modes (practice/analysis) keep their existing prompts in chat.ts
      return COACH_SYSTEM_PROMPT;
  }
}


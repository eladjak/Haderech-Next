/**
 * Normalizes a Date (or Date-like) to a YYYY-MM-DD string in the user's
 * effective timezone. We use Israel time (Asia/Jerusalem) so that "10
 * messages a day" matches the user's mental model of a day in Israel.
 */
export function toDateStr(d: Date = new Date()): string {
  const formatter = new Intl.DateTimeFormat("en-CA", {
    timeZone: "Asia/Jerusalem",
    year: "numeric",
    month: "2-digit",
    day: "2-digit",
  });
  // en-CA gives YYYY-MM-DD natively
  return formatter.format(d);
}

/**
 * Free-tier daily message limit. Centralized here so both action + UI agree.
 */
export const FREE_DAILY_LIMIT = 10;

/**
 * Pure rate-limit check. Returns whether the user can send + remaining count.
 * Kept pure (no DB access) for unit testing.
 */
export function checkRateLimit(
  used: number,
  limit: number = FREE_DAILY_LIMIT
): { allowed: boolean; remaining: number } {
  const remaining = Math.max(0, limit - used);
  return { allowed: used < limit, remaining };
}

/**
 * Compute next reset timestamp (start of next day, Israel time).
 * Returned as epoch milliseconds.
 */
export function nextResetAt(now: Date = new Date()): number {
  const todayStr = toDateStr(now);
  // parse "YYYY-MM-DD" then add 1 day in Israel time
  // Asia/Jerusalem is UTC+2 winter / UTC+3 summer. We approximate by
  // computing midnight in Israel via the Intl trick: format midnight UTC,
  // then offset.
  const [y, m, dd] = todayStr.split("-").map((s) => parseInt(s, 10));
  // Tomorrow at 00:00 Israel time. We use UTC and shift -3 hours as a
  // pragmatic approximation (DST drift of 1h is acceptable for a UI badge).
  const tomorrowUtc = Date.UTC(y, m - 1, dd + 1, 0 - 3, 0, 0, 0);
  return tomorrowUtc;
}
